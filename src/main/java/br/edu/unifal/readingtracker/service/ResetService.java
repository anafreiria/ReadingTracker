package br.edu.unifal.readingtracker.service;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import br.edu.unifal.readingtracker.seed.SeedLoader;
import br.edu.unifal.readingtracker.seed.SeedSummary;

/**
 * Reset data (FR-07): deletes every record and loads the official seed.json again.
 *
 * <p>Reuses {@link SeedLoader#clear()} and {@link SeedLoader#load()} inside a single transaction:
 * if the seed cannot be loaded, the deletions are rolled back and the current data stays as it
 * was. IDs are generated by the database, so after a reset every record has a new, larger ID; the
 * frontend never relies on fixed IDs.
 */
@Service
public class ResetService {

	private static final Logger log = LoggerFactory.getLogger(ResetService.class);

	private final SeedLoader seedLoader;

	public ResetService(SeedLoader seedLoader) {
		this.seedLoader = seedLoader;
	}

	@Transactional
	public SeedSummary reset() {
		seedLoader.clear();
		SeedSummary summary = seedLoader.load();
		log.info("Data reset; loaded seed.json: {}", summary);
		return summary;
	}

}
